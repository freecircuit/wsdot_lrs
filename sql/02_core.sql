-- SCHEMAS

CREATE SCHEMA IF NOT EXISTS staging; -- raw datasets
CREATE SCHEMA IF NOT EXISTS transform; -- cleaning datasets
CREATE SCHEMA IF NOT EXISTS ref; -- immutable datasets
CREATE SCHEMA IF NOT EXISTS analysis; -- final tables

-- ADMINISTRATION

ALTER SCHEMA staging OWNER TO CURRENT_USER;
ALTER SCHEMA transform OWNER TO CURRENT_USER;
ALTER SCHEMA ref OWNER TO CURRENT_USER;
ALTER SCHEMA analysis OWNER TO CURRENT_USER;

-- FUTURE TABLES
-- In a multi-user production environment, replace CURRENT_USER 
-- with dedicated service roles (e.g., etl_role, analyst_role).

ALTER DEFAULT PRIVILEGES IN SCHEMA staging GRANT ALL ON TABLES TO CURRENT_USER;
ALTER DEFAULT PRIVILEGES IN SCHEMA transform GRANT ALL ON TABLES TO CURRENT_USER;
ALTER DEFAULT PRIVILEGES IN SCHEMA ref GRANT ALL ON TABLES TO CURRENT_USER;
ALTER DEFAULT PRIVILEGES IN SCHEMA analysis GRANT ALL ON TABLES TO CURRENT_USER;
